"""Build assets/namedata.js: token->gender dictionary + suffix log-odds from open name lists.
Sources: indonesian-name-gender-dataset (MIT) and Cipta-Nama (MIT). Run: python3 tools/build_namedata.py SRC_DIR [--cv]"""
import csv,re,sys,json,math,random,collections
src=sys.argv[1]; CV='--cv' in sys.argv
def load():
    rows=[]
    for r in csv.DictReader(open(f'{src}/indonesian-name-gender-dataset/name_gender.csv',encoding='utf8')):
        n=re.sub(r'[^a-z ]',' ',r['name'].lower()).split()
        if n and r['gender'] in 'mf': rows.append((n,r['gender']))
    return rows
def cipta():
    t=open(f'{src}/Cipta-Nama/src/CiptaNama.php',encoding='utf8').read()
    out=[]
    for var,g in(('namaDepanPria','m'),('namaDepanWanita','f'),('namaTengahPria','m'),('namaTengahWanita','f')):
        m=re.search(r'\$'+var+r'\s*=\s*\[(.*?)\];',t,re.S)
        for w in re.findall(r"'([^']+)'",m.group(1)):
            for p in re.sub(r'[^a-z ]',' ',w.lower()).split(): out.append(([p],g))
    return out
def train(rows):
    tok=collections.defaultdict(lambda:[0,0]); suf=collections.defaultdict(lambda:[0,0])
    for n,g in rows:
        k=0 if g=='f' else 1
        for i,t in enumerate(n):
            if len(t)<3: continue
            w=2 if i==0 else 1
            tok[t][k]+=w
            for L in(2,3,4):
                if len(t)>L: suf[t[-L:]][k]+=1
    D={}
    for t,(f,m) in tok.items():
        if f+m>=2 and max(f,m)/(f+m)>=.8: D[t]='f' if f>m else 'm'
        elif f+m==1 or (f+m>=2): pass
    # also single-count first-name tokens (strong for exact-name repeats)
    for t,(f,m) in tok.items():
        if t not in D and f+m<2 and (f==2 or m==2): D[t]='f' if f else 'm'
    S={}
    for s,(f,m) in suf.items():
        if f+m>=6:
            lo=math.log((m+1)/(f+1))
            if abs(lo)>=.9: S[s]=round(lo,1)
    return D,S
def predict(D,S,n):
    sc=0.;
    for i,t in enumerate(n):
        w=2 if i==0 else 1
        if t in D: sc+=w*(3 if D[t]=='m' else -3)
        else:
            for L in(4,3,2):
                if len(t)>L and t[-L:] in S: sc+=w*S[t[-L:]]*.6;break
    return 'm' if sc>0 else 'f' if sc<0 else None
if CV:
    rows=load(); random.seed(1); random.shuffle(rows); K=5; ok=n=un=0
    for k in range(K):
        te=rows[k::K]; tr=[r for i,r in enumerate(rows) if i%K!=k]+cipta()
        D,S=train(tr)
        for nm,g in te:
            p=predict(D,S,nm); n+=1
            if p is None: un+=1
            elif p==g: ok+=1
    print('cv acc(answered)',ok/(n-un),'coverage',1-un/n,'n',n)
    sys.exit()
rows=load()+cipta(); D,S=train(rows)
M=sorted(t for t,g in D.items() if g=='m'); F=sorted(t for t,g in D.items() if g=='f')
js='/* Generated by tools/build_namedata.py from open name lists (MIT): indonesian-name-gender-dataset, Cipta-Nama. */\nwindow.RKN={m:"%s",f:"%s",s:%s};\n'%(' '.join(M),' '.join(F),json.dumps(S,separators=(',',':')))
open('assets/namedata.js','w').write(js); print(len(M),len(F),len(S),len(js))
